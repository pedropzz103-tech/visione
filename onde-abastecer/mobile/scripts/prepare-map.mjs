import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const js = readFileSync(path.join(root, 'node_modules/leaflet/dist/leaflet.js'), 'utf8');
const css = readFileSync(path.join(root, 'src/components/leaflet.css'), 'utf8');
const license = readFileSync(path.join(root, 'node_modules/leaflet/LICENSE'), 'utf8');
const shell = readFileSync(path.join(root, 'src/components/android-map.html'), 'utf8');
const html = shell.replace('/* LEAFLET_CSS */', () => css).replace('/* LEAFLET_JS */', () => js.replace(/<\/script/gi, '<\\/script')).replace('LEAFLET_LICENSE', license.replace(/--/g, '—'));
const out = path.join(root, 'src/generated');
mkdirSync(out, { recursive: true });
writeFileSync(path.join(out, 'mapDocument.ts'), `// Generated by scripts/prepare-map.mjs from pinned Leaflet; do not edit.\nexport const mapHtml = ${JSON.stringify(html)};\n`);
console.log('Prepared bundled Leaflet Android map (no remote scripts).');
